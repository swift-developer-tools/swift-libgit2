    case gitErrorReference
    
    /// The error is related to ZLib.
    case gitErrorZLib
    
    /// The error is related to the repository.
    case gitErrorRepository
    
    /// The error is related to the configuration.
    case gitErrorConfig
    
    /// The error is related to a regular expression.
    case gitErrorRegex
    
    /// The error is related to the object database.
    case gitErrorODB
    
    /// The error is related to the index.
    case gitErrorIndex
    
    /// The error is related to an object.
    case gitErrorObject
    
    /// The error is related to a network operation.
    case gitErrorNet
    
    /// The error is related to a tag.
    case gitErrorTag
    
    /// The error is related to a tree.
    case gitErrorTree
    
    /// The error is related to an indexer.
    case gitErrorIndexer
    
    /// The error is related to SSL.
    case gitErrorSSL
    
    /// The error is related to a submodule.
    case gitErrorSubmodule
    
    /// The error is related to a thread.
    case gitErrorThread
    
    /// The error is related to a stash.
    case gitErrorStash
    
    /// The error is related to a checkout operation.
    case gitErrorCheckout
    
    /// The error is related to `FETCH_HEAD`.
    case gitErrorFETCHHEAD
    
    /// The error is related to a merge operation.
    case gitErrorMerge
    
    /// The error is related to SSH.
    case gitErrorSSH
    
    /// The error is related to filtering.
    case gitErrorFilter
    
    /// The error is related to a revert operation.
    case gitErrorRevert
    
    /// The error is related to a callback.
    case gitErrorCallback
    
    /// The error is related to a cherrypick operation.
    case gitErrorCherrypick
    
    /// The error is related to a describe operation.
    case gitErrorDescribe
    
    /// The error is related to a rebase operation.
    case gitErrorRebase
    
    /// The error is related to the file system.
    case gitErrorFileSystem
    
    /// The error is related to a patch operation.
    case gitErrorPatch
    
    /// The error is related to a worktree.
    case gitErrorWorktree
    
    /// The error is related to a SHA ID.
    case gitErrorSHA
    
    /// The error is related to HTTP.
    case gitErrorHTTP
    
    /// The error is an internal error.
    case gitErrorInternal
    

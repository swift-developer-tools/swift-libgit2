import CLibgit2



/// These enums specify additional protocols beyond ``CEnum`` for
/// documentation purposes.
///
/// Enums that can use a simple raw value type get automatic `Equatable`,
/// `Hashable`, and `RawRepresentable` conformance, which DocC automatically
/// documents. However, these enums implement `RawRepresentable` manually to
/// support an unknown case with an associated value, which prevents automatic
/// conformance.
///
/// Explicitly declaring `Equatable`, `Hashable`, and `RawRepresentable`
/// conformance ensures that DocC includes these protocol implementations in
/// the generated documentation, maintaining consistency with the documentation
/// of other enums.



/// Operation result codes.
///
/// Despite its name, this enum represents both success and error codes.
/// The ``GitErrorCode/gitOK`` case indicates a successful operation, while
/// all other cases represent various error conditions.
///
/// Some libgit2 functions also return non-zero values from caller-provided
/// callbacks. These callback return values will be wrapped in the
/// ``GitErrorCode/gitUnknown(_:)`` case.
///
/// ## C Equivalent
///
/// [`git_error_code`](https://libgit2.org/docs/reference/main/errors/git_error_code.html)
public enum GitErrorCode: CEnum, Equatable, Hashable, RawRepresentable
{
    /// No error occurred, and the operation was successful.
    case gitOK
    
    /// An error occurred.
    ///
    /// Callers should call ``gitErrorLast()`` for more information.
    case gitError
    
    /// The requested object could not be found.
    case gitENotFound
    
    /// The object already exists, preventing the operation.
    case gitEExists
    
    /// More than one object matches the query.
    case gitEAmbiguous
    
    /// The output buffer is too short to hold the data.
    case gitEBufs
    
    /// A special error that is never generated by libgit2.
    ///
    /// Callers may return this error from a callback to know that it was
    /// generated by the callback and not by libgit2.
    ///
    /// - Important: swift-libgit2 functions will return this error code if
    /// a parameter could not be converted from Swift to C, or in other cases
    /// specific to individual functions.
    case gitEUser
    
    /// The operation is not allowed on a bare repository.
    case gitEBareRepo
    
    /// HEAD refers to a branch with no commits.
    case gitEUnbornBranch
    
    /// An in-progress merge prevented the operation.
    case gitEUnmerged
    
    /// The reference is not fast-forwardable.
    case gitENonFastForward
    
    /// The name or refspec is not valid.
    case gitEInvalidSpec
    
    /// A checkout conflict prevented the operation.
    case gitEConflict
    
    /// A locked file prevented the operation.
    case gitELocked
    
    /// The reference value does not match the expected value.
    case gitEModified
    
    /// An authentication error occurred.
    case gitEAuth
    
    /// The server certificate is invalid.
    case gitECertificate
    
    /// The patch or merge has already been applied.
    case gitEApplied
    
    /// The requested peel operation is not possible.
    case gitEPeel
    
    /// An unexpected EOF was encountered.
    case gitEEOF
    
    /// An invalid operation or input occurred.
    case gitEInvalid
    
    /// Uncommitted changes in the index prevented the operation.
    case gitEUncommitted
    
    /// The operation is not valid for a directory.
    case gitEDirectory
    
    /// A merge conflict exists and cannot continue.
    case gitEMergeConflict
    
    /// A callback refused to act.
    case gitPassthrough
    
    /// Iteration is over.
    case gitIterOver
    
    /// An internal libgit2 result code.
    case gitRetry
    
    /// An object hashsum mismatch occurred.
    case gitEMismatch
    
    /// The operation would overwrite unsaved changes in the index.
    case gitEIndexDirty
    
    /// The patch application failed.
    case gitEApplyFail
    
    /// The object is not owned by the current user.
    case gitEOwner
    
    /// The operation timed out.
    case gitTimeout
    
    /// There were no changes.
    case gitEUnchanged
    
    /// An option is not supported.
    case gitENotSupported
    
    /// The subject is read-only.
    case gitEReadOnly
    
    /// An unknown or undocumented libgit2 result code.
    case gitUnknown(Int32)
    
    
    
    /// Initializes a ``GitErrorCode`` instance from the given raw value.
    /// - Parameter rawValue: The raw value to use.
    public init(
        rawValue: Int32
    )
    {
        switch rawValue
        {
            case 0      : self = .gitOK
            case -1     : self = .gitError
            case -3     : self = .gitENotFound
            case -4     : self = .gitEExists
            case -5     : self = .gitEAmbiguous
            case -6     : self = .gitEBufs
            case -7     : self = .gitEUser
            case -8     : self = .gitEBareRepo
            case -9     : self = .gitEUnbornBranch
            case -10    : self = .gitEUnmerged
            case -11    : self = .gitENonFastForward
            case -12    : self = .gitEInvalidSpec
            case -13    : self = .gitEConflict
            case -14    : self = .gitELocked
            case -15    : self = .gitEModified
            case -16    : self = .gitEAuth
            case -17    : self = .gitECertificate
            case -18    : self = .gitEApplied
            case -19    : self = .gitEPeel
            case -20    : self = .gitEEOF
            case -21    : self = .gitEInvalid
            case -22    : self = .gitEUncommitted
            case -23    : self = .gitEDirectory
            case -24    : self = .gitEMergeConflict
            case -30    : self = .gitPassthrough
            case -31    : self = .gitIterOver
            case -32    : self = .gitRetry
            case -33    : self = .gitEMismatch
            case -34    : self = .gitEIndexDirty
            case -35    : self = .gitEApplyFail
            case -36    : self = .gitEOwner
            case -37    : self = .gitTimeout
            case -38    : self = .gitEUnchanged
            case -39    : self = .gitENotSupported
            case -40    : self = .gitEReadOnly
            default     : self = .gitUnknown(rawValue)
        }
    }
    
    
    
    /// The raw value.
    public var rawValue: Int32
    {
        switch self
        {
            case .gitOK                 : return 0
            case .gitError              : return -1
            case .gitENotFound          : return -3
            case .gitEExists            : return -4
            case .gitEAmbiguous         : return -5
            case .gitEBufs              : return -6
            case .gitEUser              : return -7
            case .gitEBareRepo          : return -8
            case .gitEUnbornBranch      : return -9
            case .gitEUnmerged          : return -10
            case .gitENonFastForward    : return -11
            case .gitEInvalidSpec       : return -12
            case .gitEConflict          : return -13
            case .gitELocked            : return -14
            case .gitEModified          : return -15
            case .gitEAuth              : return -16
            case .gitECertificate       : return -17
            case .gitEApplied           : return -18
            case .gitEPeel              : return -19
            case .gitEEOF               : return -20
            case .gitEInvalid           : return -21
            case .gitEUncommitted       : return -22
            case .gitEDirectory         : return -23
            case .gitEMergeConflict     : return -24
            case .gitPassthrough        : return -30
            case .gitIterOver           : return -31
            case .gitRetry              : return -32
            case .gitEMismatch          : return -33
            case .gitEIndexDirty        : return -34
            case .gitEApplyFail         : return -35
            case .gitEOwner             : return -36
            case .gitTimeout            : return -37
            case .gitEUnchanged         : return -38
            case .gitENotSupported      : return -39
            case .gitEReadOnly          : return -40
            case .gitUnknown(let code)  : return code
        }
    }
    
    
    
    /// Initializes a ``GitErrorCode`` instance from the given `git_error_code`
    /// instance.
    /// - Parameter error: The `git_error_code` instance to use.
    internal init?(
        cValue error: git_error_code
    )
    {
        switch error
        {
            case GIT_OK                 : self = .gitOK
            case GIT_ERROR              : self = .gitError
            case GIT_ENOTFOUND          : self = .gitENotFound
            case GIT_EEXISTS            : self = .gitEExists
            case GIT_EAMBIGUOUS         : self = .gitEAmbiguous
            case GIT_EBUFS              : self = .gitEBufs
            case GIT_EUSER              : self = .gitEUser
            case GIT_EBAREREPO          : self = .gitEBareRepo
            case GIT_EUNBORNBRANCH      : self = .gitEUnbornBranch
            case GIT_EUNMERGED          : self = .gitEUnmerged
            case GIT_ENONFASTFORWARD    : self = .gitENonFastForward
            case GIT_EINVALIDSPEC       : self = .gitEInvalidSpec
            case GIT_ECONFLICT          : self = .gitEConflict
            case GIT_ELOCKED            : self = .gitELocked
            case GIT_EMODIFIED          : self = .gitEModified
            case GIT_EAUTH              : self = .gitEAuth
            case GIT_ECERTIFICATE       : self = .gitECertificate
            case GIT_EAPPLIED           : self = .gitEApplied
            case GIT_EPEEL              : self = .gitEPeel
            case GIT_EEOF               : self = .gitEEOF
            case GIT_EINVALID           : self = .gitEInvalid
            case GIT_EUNCOMMITTED       : self = .gitEUncommitted
            case GIT_EDIRECTORY         : self = .gitEDirectory
            case GIT_EMERGECONFLICT     : self = .gitEMergeConflict
            case GIT_PASSTHROUGH        : self = .gitPassthrough
            case GIT_ITEROVER           : self = .gitIterOver
            case GIT_RETRY              : self = .gitRetry
            case GIT_EMISMATCH          : self = .gitEMismatch
            case GIT_EINDEXDIRTY        : self = .gitEIndexDirty
            case GIT_EAPPLYFAIL         : self = .gitEApplyFail
            case GIT_EOWNER             : self = .gitEOwner
            case GIT_TIMEOUT            : self = .gitTimeout
            case GIT_EUNCHANGED         : self = .gitEUnchanged
            case GIT_ENOTSUPPORTED      : self = .gitENotSupported
            case GIT_EREADONLY          : self = .gitEReadOnly
            default                     : return nil
        }
    }
    
    
    
    /// Converts the ``GitErrorCode`` instance into a `git_error_code` instance.
    ///
    /// This method returns `GIT_EUSER` for the ``GitErrorCode/gitUnknown(_:)``
    /// case.
    ///
    /// The ``CEnum`` protocol requires conformance to ``CConvertible``,
    /// which requires a non-throwing conversion method. An alternative design
    /// would be to not conform to ``CEnum``, and instead directly conform to
    /// ``ThrowingCConvertible`` and the other necessary protocols, allowing
    /// this method to throw an error for unknown result codes.
    ///
    /// However, any thrown error would be caught by ``withCConversion(_:)``
    /// and converted to `GIT_EUSER` anyway, making the throwing variant
    /// functionally equivalent to the non-throwing variant, while creating
    /// unnecessary inconsistency with other enums.
    ///
    /// - Returns: The `git_error_code` instance.
    internal func cValue() -> git_error_code
    {
        switch self
        {
            case .gitOK                 : return GIT_OK
            case .gitError              : return GIT_ERROR
            case .gitENotFound          : return GIT_ENOTFOUND
            case .gitEExists            : return GIT_EEXISTS
            case .gitEAmbiguous         : return GIT_EAMBIGUOUS
            case .gitEBufs              : return GIT_EBUFS
            case .gitEUser              : return GIT_EUSER
            case .gitEBareRepo          : return GIT_EBAREREPO
            case .gitEUnbornBranch      : return GIT_EUNBORNBRANCH
            case .gitEUnmerged          : return GIT_EUNMERGED
            case .gitENonFastForward    : return GIT_ENONFASTFORWARD
            case .gitEInvalidSpec       : return GIT_EINVALIDSPEC
            case .gitEConflict          : return GIT_ECONFLICT
            case .gitELocked            : return GIT_ELOCKED
            case .gitEModified          : return GIT_EMODIFIED
            case .gitEAuth              : return GIT_EAUTH
            case .gitECertificate       : return GIT_ECERTIFICATE
            case .gitEApplied           : return GIT_EAPPLIED
            case .gitEPeel              : return GIT_EPEEL
            case .gitEEOF               : return GIT_EEOF
            case .gitEInvalid           : return GIT_EINVALID
            case .gitEUncommitted       : return GIT_EUNCOMMITTED
            case .gitEDirectory         : return GIT_EDIRECTORY
            case .gitEMergeConflict     : return GIT_EMERGECONFLICT
            case .gitPassthrough        : return GIT_PASSTHROUGH
            case .gitIterOver           : return GIT_ITEROVER
            case .gitRetry              : return GIT_RETRY
            case .gitEMismatch          : return GIT_EMISMATCH
            case .gitEIndexDirty        : return GIT_EINDEXDIRTY
            case .gitEApplyFail         : return GIT_EAPPLYFAIL
            case .gitEOwner             : return GIT_EOWNER
            case .gitTimeout            : return GIT_TIMEOUT
            case .gitEUnchanged         : return GIT_EUNCHANGED
            case .gitENotSupported      : return GIT_ENOTSUPPORTED
            case .gitEReadOnly          : return GIT_EREADONLY
            default                     : return GIT_EUSER
        }
    }
}



